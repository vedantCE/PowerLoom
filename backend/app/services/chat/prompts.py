def build_system_instruction_with_context(context_text: str) -> str:
    """Combine the core system prompt with the dynamically generated Powerloom context."""
    return f"{SYSTEM_PROMPT}\n\n========================================\nCURRENT POWERLOOM CONTEXT\n========================================\n{context_text}"
